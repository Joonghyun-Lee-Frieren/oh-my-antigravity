#!/usr/bin/env node
// Generate Antigravity entrypoints from the retained command protocol sources.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const checking = process.argv.includes('--check');
let stale = false;
function emit(relative, content) {
  const target = path.join(root, relative);
  if (checking) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) { console.error(`Stale skill artifact: ${relative}`); stale = true; }
  } else {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, content);
  }
}
for (const file of fs.readdirSync(path.join(root, 'protocols/oma')).sort()) {
  if (!file.endsWith('.toml')) continue;
  const source = fs.readFileSync(path.join(root, 'protocols/oma', file), 'utf8');
  const description = /^description = "(.*)"/m.exec(source)?.[1];
  const protocol = /prompt = """\r?\n([\s\S]*?)\r?\n"""/.exec(source)?.[1];
  if (!description || !protocol) throw new Error(`Cannot parse command source ${file}`);
  const name = `oma-${file.slice(0, -5)}`;
  const body = protocol.replace(/\$ARGUMENTS/g, 'Use the user request following this skill invocation.').replace(/\/oma:([a-z-]+)/g, '/oma-$1').replace(/Gemini CLI/g, 'Antigravity CLI').replace(/\r\n/g, '\n');
  emit(`skills/${name}/references/protocol.md`, `<!-- Generated by scripts/build-skills.mjs from protocols/oma/${file}. -->\n\nFollow the [guard contract](../../../docs/guide/guarded-workflow.md) first. It overrides legacy shared-state writes and same-turn execution. Save auxiliary notes under .omg/drafts/.\n\n${body}\n`);
  emit(`skills/${name}/SKILL.md`, `---\nname: ${name}\ndescription: ${JSON.stringify(description)}\n---\n\nRead [the protocol](references/protocol.md) for this command.\nFor code work, first read [the guard contract](../../docs/guide/guarded-workflow.md).\nThe guard contract takes precedence over legacy state-writing or same-turn execution instructions.\nOnly the owning main conversation writes code; subagents return read-only handoffs.\n`);
}
if (stale) process.exitCode = 1;
